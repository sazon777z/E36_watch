// =============================================================================
// ЭНЕРГОСБЕРЕЖЕНИЕ (ПОСТОЯННОЕ ПИТАНИЕ + ГЛУБОКИЙ СОН)
// =============================================================================
// Плата засыпает, когда CAN-шина молчит (зажигание выключено), и просыпается
// по первому доминантному биту на CAN RX (MS2 начал вещание) или по кнопке.
