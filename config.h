#include <Arduino.h>

// =============================================================================
// НАЗНАЧЕНИЕ ПИНОВ (PINOUT) ESP32-S3
// =============================================================================
// Дисплей GMT024-08 (ST7789 SPI TFT 240x320)
#define PIN_TFT_SCL       13  // SPI Clock (SCK)
